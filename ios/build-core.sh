#!/bin/sh
# Prepares what the iPhone app bundles, in ios/SFDesk/Generated (not in git):
#   core-bundle.js  the shared core (src/sha1.js, router.js, store.js, core.js) and Host/host.js as one script
#                   for JavaScriptCore, which can't load ES modules: each module is wrapped in a function
#                   returning what it exports, and its imports of the others are dropped.
#   web/            the page (public/)
# Run by the Xcode build and by ios/build-mac-test.sh.
set -eu
cd "$(dirname "$0")/.."
OUT=ios/SFDesk/Generated
mkdir -p "$OUT"
rm -rf "$OUT/web" && cp -R public "$OUT/web"

bundle="$OUT/core-bundle.js.tmp"
printf '// Generated by ios/build-core.sh from src/ and ios/SFDesk/Host/host.js. Do not edit.\n"use strict";\n' > "$bundle"
for f in src/sha1.js src/router.js src/store.js src/core.js; do
  names=$( { grep -oE '^export (async )?(function|const|let|class) [A-Za-z_$][A-Za-z0-9_$]*' "$f" | awk '{print $NF}';
             grep -oE '^export \{[^}]*\}' "$f" | sed -e 's/^export {//' -e 's/}//' | tr ',' '\n'; } | tr -d ' ' | grep -v '^$' | paste -sd, -)
  [ -n "$names" ] || { echo "No exports found in $f" >&2; exit 1; }
  printf '\n// ---- %s ----\nconst { %s } = (() => {\n' "$f" "$names" >> "$bundle"
  # Imports of the other shared modules come from the wrappers above; anything else can't run here.
  if grep -E '^import ' "$f" | grep -vqE "from '\./[a-z0-9]+\.js';$"; then echo "$f imports something outside src/" >&2; exit 1; fi
  grep -vE "^import .* from '\./[a-z0-9]+\.js';$" "$f" | grep -vE '^export \{[^}]*\};?$' | sed -e 's/^export //' >> "$bundle"
  printf '\nreturn { %s };\n})();\n' "$names" >> "$bundle"
done
printf '\n// ---- ios/SFDesk/Host/host.js ----\n' >> "$bundle"
cat ios/SFDesk/Host/host.js >> "$bundle"
mv "$bundle" "$OUT/core-bundle.js"
echo "Built $OUT/core-bundle.js ($(wc -c < "$OUT/core-bundle.js" | tr -d ' ') bytes) and $OUT/web"
